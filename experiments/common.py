"""Shared helpers for reproducible OmniGuard V2X experiment scaffolds."""

from __future__ import annotations

import csv
import json
from dataclasses import asdict, is_dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, Iterable, List, Sequence


FRAMEWORK_STATUS = "framework_only_no_benchmark_results"
TODO_STATUS = "TODO_DATASET_OR_DEPLOYMENT_REQUIRED"
DEFAULT_REPORT_DIR = Path(__file__).resolve().parent / "reports"


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def repo_root() -> Path:
    return Path(__file__).resolve().parents[1]


def ensure_dir(path: Path) -> Path:
    path.mkdir(parents=True, exist_ok=True)
    return path


def to_plain(value: Any) -> Any:
    if is_dataclass(value):
        return asdict(value)
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, list):
        return [to_plain(v) for v in value]
    if isinstance(value, tuple):
        return [to_plain(v) for v in value]
    if isinstance(value, dict):
        return {str(k): to_plain(v) for k, v in value.items()}
    return value


def write_json(path: Path, payload: Dict[str, Any]) -> Path:
    ensure_dir(path.parent)
    path.write_text(json.dumps(to_plain(payload), indent=2, sort_keys=True), encoding="utf-8")
    return path


def write_csv(path: Path, rows: Sequence[Dict[str, Any]], fieldnames: Sequence[str]) -> Path:
    ensure_dir(path.parent)
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(fieldnames), extrasaction="ignore")
        writer.writeheader()
        for row in rows:
            writer.writerow({k: to_plain(row.get(k, "")) for k in fieldnames})
    return path


def write_markdown_report(path: Path, title: str, summary: Dict[str, Any], rows: Sequence[Dict[str, Any]]) -> Path:
    ensure_dir(path.parent)
    lines = [
        f"# {title}",
        "",
        "This report is generated by the reproducible experiment framework.",
        "It does not contain benchmark results unless a real dataset/deployment runner is connected.",
        "",
        "## Summary",
        "",
    ]
    for key, value in summary.items():
        lines.append(f"- `{key}`: `{value}`")
    lines.extend(["", "## TODO", ""])
    lines.extend([
        "- Connect real datasets, deployment harnesses, or benchmark commands.",
        "- Record raw logs and environment metadata for every completed run.",
        "- Replace TODO rows only with measured values produced by a reproducible runner.",
    ])
    if rows:
        lines.extend(["", "## Planned Configurations", ""])
        preview = rows[:10]
        keys = list(preview[0].keys())
        lines.append("| " + " | ".join(keys) + " |")
        lines.append("| " + " | ".join(["---"] * len(keys)) + " |")
        for row in preview:
            lines.append("| " + " | ".join(str(row.get(k, "")) for k in keys) + " |")
        if len(rows) > len(preview):
            lines.append("")
            lines.append(f"Showing first {len(preview)} of {len(rows)} planned configurations.")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def write_no_results_png(path: Path, title: str, subtitle: str) -> Path:
    """Create a PNG saying no benchmark results are present.

    This is a plot artifact for reproducibility reports, not a benchmark chart.
    """
    ensure_dir(path.parent)
    try:
        import matplotlib.pyplot as plt

        fig, ax = plt.subplots(figsize=(8, 4.5))
        ax.axis("off")
        ax.text(0.5, 0.62, title, ha="center", va="center", fontsize=15, weight="bold")
        ax.text(0.5, 0.42, subtitle, ha="center", va="center", fontsize=10, wrap=True)
        fig.tight_layout()
        fig.savefig(path, dpi=160)
        plt.close(fig)
    except Exception:
        # Minimal valid 1x1 transparent PNG fallback.
        path.write_bytes(
            bytes.fromhex(
                "89504e470d0a1a0a0000000d49484452000000010000000108060000001f15c489"
                "0000000d49444154789c6360000002000100ffff03000006000557bfab3d000000"
                "0049454e44ae426082"
            )
        )
    return path


def artifact_manifest(paths: Iterable[Path]) -> List[str]:
    return [str(p) for p in paths]

